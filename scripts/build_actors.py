def expected_files() -> dict[Path, str | bytes]:
    files: dict[Path, str | bytes] = {}
    for actor in ACTORS:
        base = ROOT / 'actors' / actor.slug
        files[base / '.actor' / 'actor.json'] = dump(actor_json(actor))
        files[base / '.actor' / 'input_schema.json'] = dump(input_schema(actor))
        files[base / '.actor' / 'dataset_schema.json'] = dump(dataset_schema(actor))
        files[base / '.actor' / 'output_schema.json'] = dump(output_schema(actor))
        files[base / 'README.md'] = readme(actor)
        for name in SHARED_PACKAGE_FILES:
            files[base / 'my_actor' / name] = (SHARED / name).read_bytes()
        for name in SHARED_ACTOR_FILES:
            files[base / name] = (SHARED / name).read_bytes()
    return files


def main() -> int:
    check = '--check' in sys.argv[1:]
    stale: list[Path] = []
    for path, content in expected_files().items():
        data = content.encode() if isinstance(content, str) else content
        if path.exists() and path.read_bytes() == data:
            continue
        stale.append(path)
        if not check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    for actor in ACTORS:
        endpoint = ROOT / 'actors' / actor.slug / 'my_actor' / 'endpoint.py'
        if not endpoint.exists():
            print(f'missing hand-written file: {endpoint.relative_to(ROOT)}')
            return 1
    if check and stale:
        print('Out of date (run python scripts/build_actors.py):')
        print('\n'.join(f'  {path.relative_to(ROOT)}' for path in stale))
        return 1
    verb, state = ('Checked', 'stale') if check else ('Wrote', 'updated')
    print(f'{verb} {len(ACTORS)} Actors; {len(stale)} file(s) {state}.')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
