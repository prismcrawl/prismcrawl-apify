"""Generate every Actor under `actors/` from `scripts/actor_defs.py` and the shared runtime in `shared/`.

    python scripts/build_actors.py          # write files
    python scripts/build_actors.py --check  # exit 1 if any generated file is out of date

Each Actor directory must be self-contained for `apify push --dir actors/<slug>`, so the shared runtime is copied into
every Actor. Only `actors/<slug>/my_actor/endpoint.py` is written by hand; everything else here is generated.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parent))

from actor_defs import ACTORS, ROOT, ActorDef

SHARED = ROOT / 'shared'
SHARED_PACKAGE_FILES = (
    '__init__.py',
    '__main__.py',
    'main.py',
    'prismcrawl.py',
    'runtime.py',
    'standby.py',
    'py.typed',
)
SHARED_ACTOR_FILES = ('Dockerfile', 'requirements.txt', '.dockerignore', '.actorignore')
GENERATED_NOTE = '<!-- Generated by scripts/build_actors.py from scripts/actor_defs.py. Edit those, not this file. -->'
BY_SLUG = {actor.slug: actor for actor in ACTORS}


def dump(data: Any) -> str:
    return json.dumps(data, indent=4, ensure_ascii=False) + '\n'


def actor_json(actor: ActorDef) -> dict[str, Any]:
    return {
        '$schema': 'https://apify.com/schemas/v1/actor.ide.json',
        'actorSpecification': 1,
        'name': actor.name,
        'title': actor.title,
        'description': actor.description,
        'version': '0.1',
        'buildTag': 'latest',
        'usesStandbyMode': True,
        'meta': {'templateId': 'python-standby', 'generatedBy': 'Claude Code with Claude Opus 5.5'},
        'inputSchema': './input_schema.json',
        'outputSchema': './output_schema.json',
        'storages': {'dataset': './dataset_schema.json'},
        'dockerfile': '../Dockerfile',
    }


def input_schema(actor: ActorDef) -> dict[str, Any]:
    return {
        '$schema': 'https://apify.com/schemas/v1/input.ide.json',
        'title': f'{actor.title} input',
        'description': f'{actor.description} You need a PrismCrawl API key; each successful request uses one '
        'PrismCrawl credit, and failed requests are free.',
        'type': 'object',
        'schemaVersion': 1,
        'properties': actor.fields,
        'required': actor.required,
    }


def dataset_schema(actor: ActorDef) -> dict[str, Any]:
    pages_view = {
        'title': 'Pages',
        'description': 'One row per PrismCrawl request, with the complete normalized response.',
        'transformation': {'fields': ['page', 'request_id', 'success', 'credits_remaining', 'data']},
        'display': {
            'component': 'table',
            'properties': {
                'page': {'label': 'Page', 'format': 'number'},
                'request_id': {'label': 'PrismCrawl request ID', 'format': 'text'},
                'success': {'label': 'Success', 'format': 'boolean'},
                'credits_remaining': {'label': 'Credits remaining', 'format': 'number'},
                'data': {'label': 'Response data', 'format': 'object'},
            },
        },
    }
    return {
        '$schema': 'https://apify.com/schemas/v1/dataset.ide.json',
        'actorSpecification': 1,
        'fields': {
            'type': 'object',
            'description': "One item per PrismCrawl page: the PrismCrawl response body unchanged, plus the Actor's "
            'page number and the X-Credits-Remaining header value.',
            'required': ['page', 'success', 'request_id', 'data'],
            'properties': {
                'page': {'type': 'integer', 'description': '1-based page number within this run.'},
                'credits_remaining': {
                    'type': ['integer', 'null'],
                    'description': 'PrismCrawl credits remaining after this request (X-Credits-Remaining header), '
                    'or null if not returned.',
                },
                'success': {'type': 'boolean'},
                'request_id': {
                    'type': 'string',
                    'description': 'PrismCrawl request ID. Include it when contacting PrismCrawl support.',
                },
                'data': {
                    'type': 'object',
                    'description': 'PrismCrawl response data: format and content (search_parameters, results, '
                    'has_next_page, and endpoint-specific fields).',
                },
            },
        },
        'views': {**actor.views, 'pages': pages_view},
    }


def output_schema(actor: ActorDef) -> dict[str, Any]:
    first_view = next(iter(actor.views))
    return {
        '$schema': 'https://apify.com/schemas/v1/output.ide.json',
        'actorOutputSchemaVersion': 1,
        'title': f'{actor.title} output',
        'properties': {
            'results': {
                'type': 'string',
                'title': actor.views[first_view]['title'],
                'template': f'{{{{links.apiDefaultDatasetUrl}}}}/items?view={first_view}',
            },
            'responses': {
                'type': 'string',
                'title': 'Full PrismCrawl responses',
                'template': '{{links.apiDefaultDatasetUrl}}/items',
            },
        },
    }


def paginated(actor: ActorDef) -> bool:
    return 'maxPages' in actor.fields


